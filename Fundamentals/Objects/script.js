/*                Object Basics
An object in JavaScript is a collection of key-value pairs, where each key (also known as a property) is a string (or symbol) and the value can be of any data type, including other objects or functions.

Objects are used to store and manage related data and functionality in a structured way. They are fundamental to JavaScript and are used extensively in both client-side and server-side programming.
*/

/*                    Differences between Objects and Primitives
1. Data Type:
   - Primitives: Include types like string, number, boolean, null, undefined, symbol, and bigint.
   - Objects: Include arrays, functions, dates, and custom objects.
2. Mutability:
   - Primitives: Immutable, meaning their values cannot be changed after they are created.
   - Objects: Mutable, meaning their properties can be changed, added, or removed.
3. Storage:
   - Primitives: Stored directly in the variable.
   - Objects: Stored as references, meaning the variable holds a reference to the location in memory where the object is stored.
4. Comparison:
   - Primitives: Compared by value.
   - Objects: Compared by reference; two objects are equal only if they reference the same location in memory.

*/